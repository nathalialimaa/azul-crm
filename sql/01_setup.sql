-- Single writer + MERGE: chaves primárias em tabelas standard não são enforced.
CREATE OR REPLACE VIEW GOLD.CUSTOMER_ANALYTICS AS
SELECT s.id AS CUSTOMER_ID, s.payload:value_score::FLOAT AS VALUE_SCORE,
 s.payload:churn_risk::FLOAT AS CHURN_RISK,
 s.payload:priority_score::FLOAT AS PRIORITY_SCORE,
 s.payload:segment::VARCHAR AS SEGMENT,
 s.payload:model_version::VARCHAR AS MODEL_VERSION,
 c.payload:is_synthetic::BOOLEAN AS IS_SYNTHETIC
FROM GOLD.SCORES s JOIN GOLD.CUSTOMERS c ON s.id=c.id;
CREATE OR REPLACE VIEW SILVER.FARES_BY_ROUTE AS
SELECT payload:period::VARCHAR AS SALE_MONTH,
 payload:origin::VARCHAR AS ORIGIN, payload:destination::VARCHAR AS DESTINATION,
 payload:airline::VARCHAR AS AIRLINE,
 SUM(payload:fare::FLOAT*payload:seats::INTEGER)/NULLIF(SUM(payload:seats::INTEGER),0) AS WEIGHTED_FARE,
 SUM(payload:seats::INTEGER) AS SOLD_SEATS
FROM SILVER.FARES GROUP BY 1,2,3,4;
